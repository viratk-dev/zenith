#!/usr/bin/env node
/**
 * Zenith — interactive setup wizard.
 * Run: npm run setup
 * Walks through: phone number, LLM choice, WhatsApp pairing mode.
 * Writes config.yaml and .env (both gitignored).
 */
import { createInterface } from "node:readline";
import { writeFileSync, existsSync, mkdirSync } from "node:fs";

const rl = createInterface({ input: process.stdin, output: process.stdout });
const ask = (q, def = "") =>
  new Promise((res) => rl.question(`${q}${def ? ` [${def}]` : ""}: `, (a) => res(a.trim() || def)));

const C = {
  purple: "\x1b[35m", cyan: "\x1b[36m", green: "\x1b[32m",
  yellow: "\x1b[33m", dim: "\x1b[2m", bold: "\x1b[1m", reset: "\x1b[0m",
};

function banner() {
  console.log(`
${C.purple}${C.bold}  ███████╗███████╗███╗   ██╗██╗████████╗██╗  ██╗
  ╚══███╔╝██╔════╝████╗  ██║██║╚══██╔══╝██║  ██║
    ███╔╝ █████╗  ██╔██╗ ██║██║   ██║   ███████║
   ███╔╝  ██╔══╝  ██║╚██╗██║██║   ██║   ██╔══██║
  ███████╗███████╗██║ ╚████║██║   ██║   ██║  ██║
  ╚══════╝╚══════╝╚═╝  ╚═══╝╚═╝   ╚═╝   ╚═╝  ╚═╝${C.reset}
  ${C.dim}Your personal AI agent — setup wizard${C.reset}
`);
}

async function main() {
  banner();

  if (existsSync("./config.yaml")) {
    const over = await ask(`${C.yellow}config.yaml already exists. Overwrite? (y/N)${C.reset}`, "n");
    if (over.toLowerCase() !== "y") { console.log("Cancelled."); rl.close(); return; }
  }

  console.log(`\n${C.bold}Step 1 — Your WhatsApp number${C.reset}`);
  console.log(`${C.dim}Only this number can control Zenith. Digits only, with country code.${C.reset}`);
  let phone = "";
  while (!/^\d{10,15}$/.test(phone)) {
    phone = (await ask("Phone number")).replace(/\D/g, "");
    if (!/^\d{10,15}$/.test(phone)) console.log(`${C.yellow}Enter digits only, e.g. 919296933126${C.reset}`);
  }

  console.log(`\n${C.bold}Step 2 — AI model (free options)${C.reset}`);
  console.log(`  ${C.cyan}1${C.reset}) Pollinations.ai  ${C.dim}— free, no key, works instantly (recommended)${C.reset}`);
  console.log(`  ${C.cyan}2${C.reset}) Ollama (local)   ${C.dim}— runs on your machine, private, needs ollama installed${C.reset}`);
  console.log(`  ${C.cyan}3${C.reset}) OpenAI-compatible ${C.dim}— OpenRouter etc., needs API key${C.reset}`);
  const choice = await ask("Choose", "1");

  let llmBlock = "";
  if (choice === "2") {
    const model = await ask("Ollama model", "llama3.1:8b");
    llmBlock = `llm:\n  provider: "ollama"\n  model: "${model}"\n  baseUrl: "http://127.0.0.1:11434"\n  maxToolIterations: 8\n  timeoutMs: 120000`;
  } else if (choice === "3") {
    const baseUrl = await ask("API base URL", "https://openrouter.ai/api/v1");
    const model = await ask("Model", "meta-llama/llama-3.1-8b-instruct:free");
    const key = await ask("API key (saved to .env, never committed)");
    llmBlock = `llm:\n  provider: "openai-compatible"\n  model: "${model}"\n  baseUrl: "${baseUrl}"\n  maxToolIterations: 8\n  timeoutMs: 120000`;
    if (key) {
      writeFileSync("./.env", `VIRAT_AGENT_LLM_KEY=${key}\n`, { flag: "a" });
      console.log(`${C.green}✓ API key saved to .env${C.reset}`);
    }
  } else {
    llmBlock = `llm:\n  provider: "openai-compatible"\n  model: "openai"\n  baseUrl: "https://text.pollinations.ai/openai"\n  maxToolIterations: 8\n  timeoutMs: 120000`;
  }

  console.log(`\n${C.bold}Step 3 — WhatsApp pairing${C.reset}`);
  console.log(`  ${C.cyan}1${C.reset}) QR code ${C.dim}(scan with your phone — easiest if you have a second device)${C.reset}`);
  console.log(`  ${C.cyan}2${C.reset}) Pairing code ${C.dim}(enter 8-char code on your phone — no second device needed)${C.reset}`);
  const pmode = await ask("Choose", "1");

  const yaml = `# Zenith — generated by setup wizard
# Re-run: npm run setup

owner:
  phone: "${phone}"

${llmBlock}

whatsapp:
  sessionDir: "./data/wa-session"
  printQr: true
  pairingMode: "${pmode === "2" ? "code" : "qr"}"

permissions:
  global:
    allow: ["web_search", "http_fetch", "notes", "file_read", "reminders", "file_list", "read_skill"]
    deny: []
  requireApproval:
    - "exec_shell"
    - "file_write"
    - "file_edit"

memory:
  dir: "./data/memory"

gateway:
  host: "127.0.0.1"
  port: 18789

sandbox:
  roots:
    - "./data/workspace"
`;
  mkdirSync("./data", { recursive: true });
  writeFileSync("./config.yaml", yaml);
  console.log(`\n${C.green}✓ config.yaml written${C.reset}`);

  console.log(`
${C.bold}${C.green}Setup complete!${C.reset}

  ${C.cyan}npm start${C.reset}   — start Zenith
${pmode === "2"
    ? `\n  When it prints a pairing code, enter it at:\n  ${C.dim}WhatsApp > Linked devices > Link a device > Link with phone number${C.reset}\n`
    : `\n  Scan the QR code with:\n  ${C.dim}WhatsApp > Linked devices > Link a device${C.reset}\n`}
  Then send Zenith a WhatsApp message. 🎉
`);
  rl.close();
}

main().catch((e) => { console.error("Setup failed:", e.message); rl.close(); process.exit(1); });
